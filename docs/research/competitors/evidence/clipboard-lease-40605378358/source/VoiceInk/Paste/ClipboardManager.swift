import SwiftUI
import AppKit

struct ClipboardManager {
    static let pasteSessionType = NSPasteboard.PasteboardType("com.VoiceInk.PasteSession")
    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func setClipboard(
        _ text: String, transient: Bool = false, sessionID: String? = nil,
        didWrite: ((Int, Bool) -> Void)? = nil
    ) -> Bool {
        let pasteboard = NSPasteboard.general
        let ownedGeneration = pasteboard.clearContents()
        var ownsPreparation = true
        defer { didWrite?(ownedGeneration, ownsPreparation && pasteboard.changeCount == ownedGeneration) }
        func write(_ body: () -> Bool) -> Bool {
            guard pasteboard.changeCount == ownedGeneration else { ownsPreparation = false; return false }
            let written = body()
            guard pasteboard.changeCount == ownedGeneration else { ownsPreparation = false; return false }
            return written
        }
        guard write({ pasteboard.setString(text, forType: .string) }) else {
            return false
        }

        if let bundleIdentifier = Bundle.main.bundleIdentifier {
            guard write({ pasteboard.setString(bundleIdentifier, forType: sourceType) }) else { return false }
        }

        if transient {
            guard write({ pasteboard.setData(Data(), forType: transientType) }),
                  write({ pasteboard.setData(Data(), forType: autoGeneratedType) }) else { return false }
        }

        if let sessionID, !write({ pasteboard.setString(sessionID, forType: pasteSessionType) }) {
            return false
        }

        let matches = pasteboard.string(forType: .string)?.utf16.elementsEqual(text.utf16) == true
        ownsPreparation = pasteboard.changeCount == ownedGeneration
        return matches && ownsPreparation
    }

    static func copyToClipboard(_ text: String) -> Bool {
        return setClipboard(text, transient: false)
    }

    static func getClipboardContent() -> String? {
        return NSPasteboard.general.string(forType: .string)
    }
}

struct ClipboardMessageModifier: ViewModifier {
    @Binding var message: String
    
    func body(content: Content) -> some View {
        content
            .overlay(
                Group {
                    if !message.isEmpty {
                        Text(message)
                            .font(.caption)
                            .foregroundColor(.green)
                            .padding(.horizontal, 8)
                            .padding(.vertical, 4)
                            .background(Color.green.opacity(0.1))
                            .cornerRadius(4)
                            .transition(.opacity)
                            .animation(.easeInOut, value: message)
                    }
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topTrailing)
                .padding()
            )
    }
}

extension View {
    func clipboardMessage(_ message: Binding<String>) -> some View {
        self.modifier(ClipboardMessageModifier(message: message))
    }
}
